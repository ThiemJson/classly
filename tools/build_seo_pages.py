#!/usr/bin/env python3
"""Regenerates the search pages: free tools, tool hubs, the FAQ and the sitemap.

    python3 tools/build_seo_pages.py

Content lives in content/<lang>/:

- site.json — wording shared by every page in that language (navigation,
  calculator labels and results, the tools hub, the download box).
- tools/<name>.html — one page per tool: a JSON header, a line with only
  ---, then the page body as HTML. Pages in different languages that share an
  "id" are translations of each other and get hreflang links to each other.

The body may contain {{table:<target>}}, which becomes a table of the fewest
classes to attend for that target. faq.html is filled from assets/faq.json so
search engines see every answer without running JavaScript; rerun this after
editing faq.json. Never edit the generated files by hand.
"""
import html
import json
import math
import pathlib
import re
import urllib.parse

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / 'content'
BASE = 'https://thiemjason-work.site/classly/'
DEFAULT_LANG = 'en'

APP_STORE = 'https://apps.apple.com/app/id6760553317'
PLAY_STORE = 'https://play.google.com/store/apps/details?id=com.thiemjason.classattendance'
# App Store Connect → Apps → App Analytics → Campaign links shows this value
# ("pt="). Until it is set, App Store links carry no campaign.
APP_STORE_PROVIDER_TOKEN = ''

# Hand-written pages that belong in the sitemap.
STATIC_PAGES = ['', 'faq.html', 'privacy.html', 'terms.html']

GENERATED = '<!-- Generated by tools/build_seo_pages.py from content/; edit those instead. -->'


def esc(value):
    return html.escape(str(value), quote=True)


def store_links(campaign):
    """App Store and Google Play links that report which page sent the install."""
    app_store = APP_STORE
    if APP_STORE_PROVIDER_TOKEN:
        app_store += '?' + urllib.parse.urlencode({'pt': APP_STORE_PROVIDER_TOKEN, 'ct': campaign[:40], 'mt': '8'})
    referrer = urllib.parse.urlencode({'utm_source': 'classly_site', 'utm_medium': 'web', 'utm_campaign': campaign})
    play = PLAY_STORE + '&' + urllib.parse.urlencode({'referrer': referrer})
    return app_store, play


def read_page(path):
    raw = path.read_text(encoding='utf-8')
    header, _, body = raw.partition('\n---\n')
    page = json.loads(header)
    page['body'] = body.strip()
    page['lang'] = path.parent.parent.name
    return page


def minimum_table(target, labels):
    rows = []
    for held in range(10, 65, 5):
        need = math.ceil(held * target / 100 - 1e-9)
        rows.append(f'<tr><td>{held}</td><td>{need}</td><td>{held - need}</td></tr>')
    return ('<div class="table-wrap"><table class="calc-table">'
            f'<thead><tr><th>{esc(labels["held"])}</th><th>{esc(labels["min"])}</th><th>{esc(labels["missed"])}</th></tr></thead>'
            f'<tbody>{"".join(rows)}</tbody></table></div>')


WIDGET_FIELDS = {
    'standing': ['held', 'attended', 'target'],
    'plan': ['total', 'target'],
    'whatif': ['held', 'attended', 'skip', 'target'],
    'recover': ['held', 'attended', 'remaining', 'target'],
}


def widget(spec, site, index):
    kind = spec['kind']
    words = dict(site['widgets'][kind])
    words.update({k: spec[k] for k in ('title', 'hint') if k in spec})
    fields = []
    for name in WIDGET_FIELDS[kind]:
        mode = 'decimal' if name == 'target' else 'numeric'
        limits = 'min="1" max="100" step="any"' if name == 'target' else 'min="0" step="1"'
        fields.append(f'<label class="field">{esc(site["fields"][name])}'
                      f'<input name="{name}" type="number" inputmode="{mode}" {limits} value="{esc(spec["defaults"][name])}"></label>')
    count = {2: ' two', 4: ' four'}.get(len(fields), '')
    title_id = f'calc-{index}'
    return (f'<section class="calc-card" data-widget="{kind}" aria-labelledby="{title_id}">\n'
            f'  <h2 id="{title_id}">{esc(words["title"])}</h2>\n'
            f'  <p>{esc(words["hint"])}</p>\n'
            f'  <div class="fields{count}">{"".join(fields)}</div>\n'
            '  <div class="result" aria-live="polite" hidden><p class="result-headline"></p><p class="result-detail"></p></div>\n'
            '</section>')


def alternates(group):
    links = [f'<link rel="alternate" hreflang="{p["lang"]}" href="{BASE}{p["slug"]}">' for p in group]
    default = next((p for p in group if p['lang'] == DEFAULT_LANG), None)
    if default:
        links.append(f'<link rel="alternate" hreflang="x-default" href="{BASE}{default["slug"]}">')
    return links


def language_switch(page, group, sites):
    if len(group) < 2:
        return ''
    parts = []
    for other in sorted(group, key=lambda p: p['lang'] != DEFAULT_LANG):
        name = esc(sites[other['lang']]['language_name'])
        if other is page:
            parts.append(name)
        else:
            parts.append(f'<a href="/classly/{other["slug"]}" hreflang="{other["lang"]}" lang="{other["lang"]}">{name}</a>')
    return '<p class="lang-switch">' + ' · '.join(parts) + '</p>'


def download_box(site, campaign):
    app_store, play = store_links(campaign)
    box = site['download']
    return ('<div class="app-cta">\n'
            '  <img src="/classly/assets/classly-icon.png" alt="" width="56" height="56">\n'
            f'  <div><b>{esc(box["title"])}</b><span>{esc(box["text"])}</span></div>\n'
            '  <div class="actions">'
            f'<a class="btn btn-ink" href="{esc(app_store)}" rel="noopener">App Store</a>'
            f'<a class="btn btn-line" href="{esc(play)}" rel="noopener">Google Play</a></div>\n'
            '</div>')


def shell(site, lang, *, title, description, slug, head_extra, body, scripts='', og_title=None, og_description=None):
    nav = site['nav']
    footer_links = ''.join(f'<a href="{esc(href)}">{esc(label)}</a>' for label, href in nav['footer'])
    locale = f'\n  <meta property="og:locale" content="{site["og_locale"]}">' if site.get('og_locale') else ''
    return f'''<!doctype html>
<html lang="{lang}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>{esc(title)}</title>
  <meta name="description" content="{esc(description)}">
  <meta name="theme-color" content="#F7F7F5" media="(prefers-color-scheme: light)">
  <meta name="theme-color" content="#121314" media="(prefers-color-scheme: dark)">
  <meta property="og:title" content="{esc(og_title or title)}">
  <meta property="og:description" content="{esc(og_description or description)}">
  <meta property="og:image" content="{BASE}assets/classly-icon.png">
  <meta property="og:type" content="website">{locale}
  <meta property="og:url" content="{BASE}{slug}">
  <link rel="canonical" href="{BASE}{slug}">
  {head_extra}
  <link rel="icon" type="image/png" href="/classly/assets/favicon.png">
  <link rel="apple-touch-icon" href="/classly/assets/apple-touch-icon.png">
  <link rel="stylesheet" href="/classly/assets/site.css">
</head>
<body>
{GENERATED}
<header>
  <nav class="wrap" aria-label="{esc(nav['label'])}">
    <a class="brand" href="/classly/"><img src="/classly/assets/classly-icon.png" alt="" width="34" height="34">Classly</a>
    <div class="links"><a href="/classly/#features">{esc(nav['features'])}</a><a href="/classly/{site['hub']['slug']}">{esc(nav['tools'])}</a><a href="/classly/faq.html">FAQ</a><a class="btn btn-ink" href="/classly/#download">{esc(nav['download'])}</a></div>
  </nav>
</header>
<main class="wrap">
{body}
</main>
<footer><div class="wrap"><div class="footer-row"><span>© 2026 Nguyen Cao Thiem · Classly</span><nav class="footer-links" aria-label="{esc(nav['footer_label'])}">{footer_links}</nav></div></div></footer>
{scripts}
</body>
</html>
'''


def tool_page(page, group, site, sites, tools_by_id):
    lang = page['lang']
    widgets = '\n'.join(widget(spec, site, i) for i, spec in enumerate(page['widgets']))
    body = re.sub(r'\{\{table:(\d+(?:\.\d+)?)\}\}',
                  lambda m: minimum_table(float(m.group(1)), site['table']), page['body'])
    faq = ''.join(f'<details><summary>{esc(item["q"])}</summary><p>{esc(item["a"])}</p></details>'
                  for item in page.get('faq', []))
    related = []
    for other_id in page.get('related', []):
        other = tools_by_id.get((other_id, lang))
        if other:
            related.append(f'<a class="tool-link" href="/classly/{other["slug"]}"><b>{esc(other["card_title"])}</b>'
                           f'<span>{esc(other["card_text"])}</span></a>')
    calc_text = dict(site['calc'])
    calc_text.update(page.get('calc', {}))
    schema = {
        '@context': 'https://schema.org', '@type': 'WebApplication', 'name': page['h1'],
        'url': BASE + page['slug'], 'applicationCategory': 'EducationalApplication', 'operatingSystem': 'Any',
        'inLanguage': lang, 'offers': {'@type': 'Offer', 'price': '0', 'priceCurrency': 'USD'},
    }
    if page.get('faq'):
        schema = [schema, {'@context': 'https://schema.org', '@type': 'FAQPage', 'mainEntity': [
            {'@type': 'Question', 'name': item['q'], 'acceptedAnswer': {'@type': 'Answer', 'text': item['a']}}
            for item in page['faq']]}]
    head = '\n  '.join(alternates(group) + [
        '<script type="application/ld+json">' + json.dumps(schema, ensure_ascii=False) + '</script>'])
    article = f'''  <article class="doc">
    <span class="kicker">{esc(site['tool_kicker'])}</span>
    <h1>{esc(page['h1'])}</h1>
    {language_switch(page, group, sites)}
    {page['intro']}
    <div class="calc">
{widgets}
    </div>
{download_box(site, f"{page['id']}-{lang}")}
{body}
    <h2>{esc(site['faq_heading'])}</h2>
    <div class="faq">{faq}</div>
    <h2>{esc(site['related_heading'])}</h2>
    <div class="tool-grid">{''.join(related)}</div>
  </article>'''
    scripts = (f'<script>window.CALC_TEXT = {json.dumps(calc_text, ensure_ascii=False)};</script>\n'
               '<script src="/classly/assets/calculator.js"></script>')
    return shell(site, lang, title=page['title'], description=page['description'], slug=page['slug'],
                 head_extra=head, body=article, scripts=scripts, og_title=page.get('og_title'), og_description=page.get('og_description'))


def hub_page(lang, site, sites, pages):
    hub = site['hub']
    cards = ''.join(f'<a class="tool-link" href="/classly/{p["slug"]}"><b>{esc(p["card_title"])}</b>'
                    f'<span>{esc(p["card_text"])}</span></a>' for p in pages)
    group = [{'lang': other, 'slug': sites[other]['hub']['slug']} for other in sorted(sites)]
    page = next(p for p in group if p['lang'] == lang)
    body = f'''  <article class="doc">
    <span class="kicker">{esc(site['tool_kicker'])}</span>
    <h1>{esc(hub['h1'])}</h1>
    {language_switch(page, group, sites)}
    <p>{esc(hub['intro'])}</p>
    <div class="tool-grid">{cards}</div>
{download_box(site, f'tools-{lang}')}
  </article>'''
    return shell(site, lang, title=hub['title'], description=hub['description'], slug=hub['slug'],
                 head_extra='\n  '.join(alternates(group)), body=body), group


def build_faq():
    """Writes every FAQ answer into faq.html so it is readable without JavaScript."""
    data = json.loads((ROOT / 'assets/faq.json').read_text(encoding='utf-8'))
    groups = []
    entities = []
    for category in data['categories']:
        items = []
        for item in category['items']:
            items.append(f'<details id="{esc(item["id"])}"><summary>{esc(item["q"])}</summary>'
                         f'<div class="answer">{item["a"]}</div></details>')
            entities.append({'@type': 'Question', 'name': item['q'],
                             'acceptedAnswer': {'@type': 'Answer', 'text': item['a']}})
        groups.append(f'<section class="faq-group" data-category="{esc(category["id"])}">'
                      f'<h2>{esc(category["title"])}</h2><div class="faq">{"".join(items)}</div></section>')
    path = ROOT / 'faq.html'
    text = path.read_text(encoding='utf-8')
    text = re.sub(r'(<!-- faq:start -->).*?(<!-- faq:end -->)',
                  lambda m: m.group(1) + '\n' + '\n'.join(groups) + '\n' + m.group(2), text, flags=re.S)
    schema = json.dumps({'@context': 'https://schema.org', '@type': 'FAQPage', 'mainEntity': entities}, ensure_ascii=False)
    text = re.sub(r'(<!-- faq-schema:start -->).*?(<!-- faq-schema:end -->)',
                  lambda m: f'{m.group(1)}<script type="application/ld+json">{schema}</script>{m.group(2)}', text, flags=re.S)
    path.write_text(text, encoding='utf-8')


def build_sitemap(groups):
    entries = [f'  <url><loc>{BASE}{page}</loc></url>' for page in STATIC_PAGES]
    for group in groups:
        links = ''.join(f'\n    <xhtml:link rel="alternate" hreflang="{p["lang"]}" href="{BASE}{p["slug"]}"/>'
                        for p in group)
        default = next((p for p in group if p['lang'] == DEFAULT_LANG), None)
        if default and len(group) > 1:
            links += f'\n    <xhtml:link rel="alternate" hreflang="x-default" href="{BASE}{default["slug"]}"/>'
        for page in group:
            entries.append(f'  <url>\n    <loc>{BASE}{page["slug"]}</loc>{links if len(group) > 1 else ""}\n  </url>')
    (ROOT / 'sitemap.xml').write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
        + '\n'.join(entries) + '\n</urlset>\n', encoding='utf-8')


def write(slug, text):
    path = ROOT / slug / 'index.html'
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')


def main():
    sites = {d.name: json.loads((d / 'site.json').read_text(encoding='utf-8'))
             for d in sorted(CONTENT.iterdir()) if (d / 'site.json').exists()}
    pages = [read_page(p) for p in sorted(CONTENT.glob('*/tools/*.html'))]
    tools_by_id = {(p['id'], p['lang']): p for p in pages}
    groups = {}
    for page in pages:
        groups.setdefault(page['id'], []).append(page)
    for page in pages:
        write(page['slug'], tool_page(page, groups[page['id']], sites[page['lang']], sites, tools_by_id))
    sitemap_groups = []
    for lang, site in sites.items():
        listed = sorted((p for p in pages if p['lang'] == lang), key=lambda p: p.get('order', 99))
        text, group = hub_page(lang, site, sites, listed)
        write(site['hub']['slug'], text)
        if lang == DEFAULT_LANG:
            sitemap_groups.append(group)
    sitemap_groups += list(groups.values())
    build_faq()
    build_sitemap(sitemap_groups)
    print(f'{len(pages)} tool pages, {len(sites)} hubs, faq.html, sitemap.xml')


if __name__ == '__main__':
    main()
